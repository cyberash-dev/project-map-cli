import type { Heading, Root, RootContent } from "mdast";
import { toMarkdown } from "mdast-util-to-markdown";
import { gfmTableToMarkdown } from "mdast-util-gfm-table";
import {
	type DetectionSectionId,
	type ExtractionError,
	isDetectionSection,
	type ProjectMap,
	type SectionId,
} from "../../../core/domain/project-map.js";
import type { ResolvedConfig } from "../../../core/ports/config.port.js";
import type { FactSet } from "../../detect/detect.use-case.js";
import { renderDetectionSection } from "./detection-sections.js";
import { renderContexts } from "../slices/contexts/render.js";
import { renderEntities } from "../slices/entities/render.js";
import { renderEnums } from "../slices/enums/render.js";
import { renderStorage } from "../slices/storage/render.js";
import { renderWorkers } from "../slices/workers/render.js";
import {
	bulletList,
	heading,
	inlineCode,
	paragraph,
	text,
} from "./mdast-helpers.js";

/**
 * Constant by contract (project-map:DLT-020): the tool version, the timestamp
 * and the revision live in the JSON companion, because a value only a rebuild
 * changes is a merge conflict carrying no information.
 */
const LEAD_PARAGRAPH = "Generated by project-map. Do not edit by hand.";

export function renderMarkdown(
	map: ProjectMap,
	config: ResolvedConfig,
	facts: FactSet | null = null,
): string {
	const title: Heading = {
		type: "heading",
		depth: 1,
		children: [text("Project Map: "), inlineCode(map.project.name)],
	};
	const children: RootContent[] = [
		title,
		paragraph([text(LEAD_PARAGRAPH)]),
		...renderExtractionErrors(map.metadata.errors),
	];

	for (const id of config.sections) {
		const nodes = isDetectionSection(id)
			? renderDetectionSection(id, facts)
			: renderSection(id, map);
		for (const node of nodes) {
			children.push(node);
		}
	}

	const root: Root = { type: "root", children };
	return toMarkdown(root, {
		bullet: "-",
		emphasis: "_",
		fence: "`",
		fences: true,
		incrementListMarker: true,
		listItemIndent: "one",
		rule: "-",
		strong: "*",
		tightDefinitions: true,
		extensions: [gfmTableToMarkdown()],
	});
}

function renderSection(
	id: Exclude<SectionId, DetectionSectionId>,
	map: ProjectMap,
): RootContent[] {
	switch (id) {
		case "overview":
			return map.metadata.overview
				? [heading(2, "Overview"), paragraph([text(map.metadata.overview)])]
				: [];
		case "contexts":
			return renderContexts(map.contexts);
		case "entities":
			return renderEntities(map.entities);
		case "enums":
			return renderEnums(map.enums);
		case "storage":
			return renderStorage(map.storage);
		case "workers":
			return renderWorkers(map.workers);
	}
}

/**
 * Not a SectionId: no configuration turns it off, because a section left empty
 * by a throwing extractor is indistinguishable from one with nothing to report.
 */
function renderExtractionErrors(
	errors: readonly ExtractionError[],
): RootContent[] {
	if (errors.length === 0) {
		return [];
	}
	return [
		heading(2, "Extraction errors"),
		bulletList(
			errors.map((error) => ({
				type: "paragraph" as const,
				children: [inlineCode(error.section), text(`: ${error.message}`)],
			})),
		),
	];
}
